"""Generate the core's read-only boot checks from the two stock-code patchers.

The generated table contains each address/length and a CRC32 across the exact
preimages of each module. Run
with --check in tests so a source hook change cannot silently stale the core.
"""
import argparse
import re
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'mods/core-st/boot-preimages.inc'


def record(address, data):
    assert 2 <= len(data) <= 10 and address % 2 == 0
    assert 0x40000000 <= address < 0x41000000
    return address, bytes(data)


def lfo3():
    source = (ROOT / 'mods/lfo3-st/main.c').read_text()
    table = source.split('sites[]={', 1)[1].split('};', 1)[0]
    rows = []
    for address, length, raw in re.findall(r'\{(0x[0-9a-f]+)u,(\d+),\{([^}]+)\}', table):
        data = [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', raw)]
        assert len(data) == int(length)
        at = int(address, 16)
        # Host API 13/14 owns these sites; LFO3 itself skips them.
        if at not in (0x400a6d96, 0x400a6d2e, 0x40013516):
            rows.append(record(at, data))
    assert len(rows) >= 80
    operands = source.split('operands[]=', 1)[1].split('};', 1)[0]
    for address, stock in re.findall(r'\{(0x[0-9a-f]+)u,(0x[0-9a-f]+),ST_SOUND_S1_BYTES\}', operands):
        at = int(address, 16)
        value = int(stock, 16)
        rows.append(record(at - 2, [0x48, 0x78, value >> 8, value & 255]))
    assert len(rows) >= 82
    return sorted(rows)


def modulation_skip():
    source = (ROOT / 'mods/modulation-skip-st/main.c').read_text()
    rows = []
    for name, expected in [('SITE', 3), ('WRITER', 4)]:
        at = int(re.search(r'#define ' + name + r' (0x[0-9a-f]+)u', source).group(1), 16)
        words = re.findall(r'be16\(' + name + r'(?:\+(\d+))?\)!=0x([0-9a-f]+)u', source)
        assert len(words) == expected
        data = bytearray(2 * expected)
        for offset, word in words:
            start = int(offset or 0)
            data[start:start + 2] = int(word, 16).to_bytes(2, 'big')
        rows.append(record(at, data))
    return sorted(rows)


def render():
    lines = ['/* Generated by tools/generate_boot_preimages.py; do not edit. */']
    for name, rows in [('lfo3', lfo3()), ('modulation_skip', modulation_skip())]:
        lines.append(f'static const u8 {name}_preimages[]={{')
        crc = 0
        for address, data in rows:
            offset = address - 0x40000000
            row = [*offset.to_bytes(3, 'big'), len(data)]
            lines.append('    ' + ','.join(f'0x{x:02x}' for x in row) + ',')
            crc = zlib.crc32(data, crc)
        lines.append('};')
        lines.append(f'#define {name.upper()}_PREIMAGES {len(rows)}u')
        lines.append(f'#define {name.upper()}_PREIMAGE_CRC 0x{crc:08x}u')
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    content = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != content:
            raise SystemExit('boot preimages differ from patcher sources; regenerate')
        print('PASS: boot preimages match LFO3 and MODULATION SKIP sources')
    else:
        OUT.write_text(content)
        print(f'Wrote {OUT}')


if __name__ == '__main__':
    main()
