"""Write mods/icache-lock-st/lines.c from an exact MAIN profile taken with
XPROF_CACHE=1 (analog-emu-xprof.patch). For each of the I-cache's 128 sets it
takes the two stock MAIN code lines that missed most often; those fill ways 0
and 1, which CACR[IHLCK] then keeps.

  gen_lock_table.py PROFILE OUT.c "scenario text"
"""
import collections
import sys

MAIN_LO, MAIN_HI = 0x40000400, 0x40348B90   # OS 1.42 MAIN image (decoded)
SETS, WAYS = 128, 2


def main(profile, out, scenario):
    lines, blocks = {}, 0
    for row in open(profile):
        f = row.split()
        if f[0] == 'iline':
            lines[int(f[1], 16)] = int(f[2])
        elif f[0] == 'calls' and int(f[1], 16) & ~1 == 0x400A38CE:
            blocks += int(f[2])
    if not lines or not blocks:
        sys.exit("profile has no I-cache lines or no audio blocks (run with XPROF_CACHE=1)")
    per_set = collections.defaultdict(list)
    for line, n in lines.items():
        a = line << 4
        if MAIN_LO <= a and a + 16 <= MAIN_HI:
            per_set[line & (SETS - 1)].append((n, line))
    tags, saved = [], 0
    for s in range(SETS):
        best = sorted(per_set[s], reverse=True)[:WAYS]
        if len(best) < WAYS:
            sys.exit(f"set {s} has fewer than {WAYS} candidate lines")
        for n, line in best:
            tag = ((line << 4) - 0x40000000) >> 11
            assert tag < 0xFFFF and 0x40000000 + (tag << 11) + (s << 4) == line << 4
            tags.append(tag)
            saved += n
    with open(out, 'w', newline='\n') as o:
        o.write("/* SPDX-License-Identifier: GPL-2.0-or-later\n"
                " * Generated by tools/stock-profile/gen_lock_table.py; do not edit.\n"
                f" * Profile: {scenario}; {blocks} audio blocks.\n"
                f" * These lines missed {saved / blocks:.0f} times per block before locking.\n"
                " * Entry 2*s+w: line = 0x40000000 + (tag << 11) + (s << 4), set s, way w. */\n"
                "const unsigned short icache_lock_tags[256] __attribute__((aligned(4)))={\n")
        for i in range(0, len(tags), 8):
            o.write("    " + ",".join(f"0x{t:04x}" for t in tags[i:i + 8]) + ",\n")
        o.write("};\n")
    print(f"{len(tags)} lines, {saved / blocks:.0f} misses/block before locking")


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
