"""Reproduce the FM+ table arrays from Monomachine OS 1.32B.

python mods/digimono-st/fmplus/import_tables.py <OS.syx>
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
from reference import HERE,load


def generate(os_file):
    rom,dsl,K,C,fm,X=load(os_file)
    tables={'sine':rom.fm_sine(),'ratios':tuple(rom.s24(v) for v in rom.words(*rom.FM_FLIST)),
            'tone':tuple(rom.s24(v) for v in rom.words(*rom.FM_TONE)),
            'envt':tuple(-rom.s24(v) for v in rom.words(*rom.FM_ENVT))}
    tables['inc']=tuple(fm.exact_inc(X.increment(min(0x5800,p*8//3+341))) for p in range(140*64+1))
    # 160 phases, 16-tap Hann-windowed sinc at 44.1 -> 48 kHz.
    # Causal delay 7 samples; coefficients normalized independently per phase.
    phases=[]
    for phase in range(160):
        frac=phase/160;row=[]
        for tap in range(16):
            x=tap-7+frac
            row.append((1 if x==0 else math.sin(math.pi*x)/(math.pi*x))*(.5+.5*math.cos(math.pi*x/8)) if abs(x)<8 else 0)
        total=sum(row);q=[round(v/total*(1<<15)) for v in row];q[7]+=(1<<15)-sum(q);phases.extend(q)
    tables['resample']=tuple(phases)
    assert max(abs(a-b) for a,b in zip(tables['sine'],tables['sine'][1:]))<8192
    # envt() selects even entries only; the unused odd entry 127 is +1.0.
    assert all(-(1<<23)<=v<(1<<23) for v in tables['envt'][::2])
    assert phases[7]==32768 and all(v==0 for j,v in enumerate(phases[:16]) if j!=7)
    assert all(abs(v)<65536 for v in phases)
    assert all(sum(abs(v) for v in phases[i:i+16])<131072 for i in range(0,len(phases),16))
    # Same coefficients aligned for ColdFire's fractional EMAC. Only the
    # array used by the selected backend survives compilation.
    tables['resample_q30']=tuple(v*32768 for v in phases)
    tables['sine_q29']=tuple(v*64 for v in tables['sine'])
    text='/* FM+ tables: Monomachine OS 1.32B; resampler generated by import_tables.py. */\n'
    for name,values in tables.items():
        text+=f'static const int32_t dmf_{name}[{len(values)}]={{\n'
        text+=''.join('    '+','.join(str(v) for v in values[i:i+12])+',\n' for i in range(0,len(values),12))+'};\n'
    return text,tables


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('os',type=Path);a=p.parse_args()
    text,tables=generate(a.os);out=HERE
    (out/'tables.h').write_text(text)
    (out/'tables.json').write_text(json.dumps({'os_sha256':hashlib.sha256(a.os.read_bytes()).hexdigest(),
        'tables_sha256':hashlib.sha256(text.encode()).hexdigest(),
        'lengths':{k:len(v) for k,v in tables.items()}},indent=2)+'\n')
    print('Wrote reproducible FM+ tables:',out/'tables.h')


if __name__=='__main__':main()
