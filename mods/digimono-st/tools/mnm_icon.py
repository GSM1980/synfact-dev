"""tools/mnm_icon.py: an original pixel icon of a synthesizer laid out as the Monomachine
SFX-60 (its volume knob and buttons on the left, the big dark panel in the middle with the
screen and two rows of four encoders, the column of lit buttons on the right, a band of
buttons, sixteen trig keys with their LEDs), drawn beside the type list (picker.c, the
picker's STP_LIST_ART). No Elektron artwork, name or logo: a drawing of our own.

Usage: python mods/digimono-st/tools/mnm_icon.py [--preview out.png]
   (writes mnm-icon.h; --preview also writes the icon eight times larger)
"""
import pathlib
import struct
import sys
import zlib

W, H = 52, 32
px = [[0] * W for _ in range(H)]


def on(x: int, y: int) -> None: px[y][x] = 1


def off(x: int, y: int) -> None: px[y][x] = 0


def rect(x0: int, y0: int, x1: int, y1: int, fill: bool = False, ink: int = 1) -> None:
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if fill or y in (y0, y1) or x in (x0, x1): px[y][x] = ink


def shape(x0: int, y0: int, rows, ink: int = 1) -> None:
    for dy, row in enumerate(rows):
        for dx, c in enumerate(row):
            if c == '#': px[y0 + dy][x0 + dx] = ink


# the body: a box with rounded corners, the jacks along its top edge
rect(0, 1, W - 1, H - 1)
for x, y in ((0, 1), (W - 1, 1), (0, H - 1), (W - 1, H - 1)): off(x, y)
for k in range(8): on(14 + 3 * k, 0)
# left: the volume knob, a lit LED, a square button and two small ones
shape(2, 3, ('.##.', '#..#', '#..#', '.##.'))
on(3, 9)
rect(2, 11, 5, 13)
on(2, 16); on(3, 16); on(5, 16)
# the dark panel: lit, the screen and the encoders cut out of it
rect(8, 3, 42, 16, fill=True)
rect(10, 5, 20, 14, fill=True, ink=0)          # the screen, its content as lines
for x in range(11, 16): on(x, 7)
for x in range(11, 19): on(x, 9)
for x in range(11, 14): on(x, 11)
for x in range(15, 19): on(x, 11)
for x in range(11, 17): on(x, 13)
for r in range(2):                             # two rows of four encoders
    for k in range(4):
        shape(23 + 5 * k, 5 + 5 * r, ('.##.', '####', '####', '.##.'), ink=0)
# right: a column of six buttons, each with its LED
for k in range(6):
    y = 3 + 2 * k
    on(44, y)
    for x in range(46, 50): on(x, y)
# the band of buttons under the panel, in groups
for x0 in (2, 5):
    on(x0, 19); on(x0 + 1, 19)
shape(9, 18, ('.#.', '###', '.#.'))            # the arrows
for x0 in (15, 18, 21, 24):
    on(x0, 19); on(x0 + 1, 19)
for x0 in (30, 33, 36):
    on(x0, 19); on(x0 + 1, 19)
for x0 in (42, 46):
    on(x0, 19); on(x0 + 1, 19)
# sixteen trig keys, a pattern lit on their LEDs
for k, lit in enumerate('1000100010101001'):
    x = 2 + 3 * k
    rect(x, 26, x + 1, 27, fill=True)
    if lit == "1": on(x, 24); on(x + 1, 24)

def header() -> str:
    """mnm-icon.h: a row two 32-bit words (no 64-bit shifts on the target), bit 31 of the
    first its left pixel, the top row first"""
    rows = []
    for r in px:
        v = 0
        for b in r: v = (v << 1) | b
        v <<= 64 - W
        rows.append((v >> 32, v & 0xffffffff))
    return ('/* SPDX-License-Identifier: GPL-2.0-or-later\n'
            ' * Generated by tools/mnm_icon.py; do not edit. An original drawing of a synthesizer\n'
            ' * laid out as the Monomachine, beside the type list (picker.c). A row is two words,\n'
            ' * bit 31 of the first its left pixel, the top row first. */\n'
            '#define DM_ICON_W %d\n#define DM_ICON_H %d\n' % (W, H) +
            'static const unsigned int dm_icon[DM_ICON_H][2]={\n' +
            ',\n'.join('    {0x%08xu,0x%08xu}' % r for r in rows) + '};\n')


def png(path: pathlib.Path, scale: int = 8) -> None:
    """the icon as the screen shows it, lit pixels white on black, scale times larger,
    with a faint grid"""
    w, h = W * scale, H * scale
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            lit = px[y // scale][x // scale]
            grid = x % scale == 0 or y % scale == 0
            raw += b'\xff\xff\xff' if lit else (b'\x30\x30\x30' if grid else b'\x00\x00\x00')
    def chunk(tag, data):
        c = struct.pack('>I', len(data)) + tag + data
        return c + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)) +
                     chunk(b'IDAT', zlib.compress(bytes(raw), 9)) + chunk(b'IEND', b''))


if __name__ == '__main__':
    out = pathlib.Path(__file__).resolve().parents[1] / 'mnm-icon.h'
    out.write_bytes(header().encode())
    print('wrote', out.name)
    if '--preview' in sys.argv:
        target = pathlib.Path(sys.argv[sys.argv.index('--preview') + 1])
        png(target)
        print('wrote', target)
