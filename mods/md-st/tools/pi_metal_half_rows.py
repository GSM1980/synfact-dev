"""tools/pi_metal_half_rows.py: the metal voices' filter rows at half rate.

PI-RC, CC and HH share two banks of filter rows (md-tables.c md_pi_cc_curve_a and _b, 128
rows of c0, c1, c2, c3). A row is y(n) = a y(n-1) + b y(n-2) + c2 x(n) + c3 x(n+1) + c2 x(n+2),
a = 1 + 2 c1, b = c0. For MD_PI_HALF (native/pi_metal_half.c) each row becomes the filter
that, at 22.05 kHz, answers as the row does at 44.1 kHz under 11 kHz:
- poles r e^(+-i t): r^2 e^(+-2 i t) while t <= pi/2, else r^2 at pi (11 kHz); real poles
  squared, a negative one kept negative (at 11 kHz);
- the zeros of c2 z^2 + c3 z + c2 the same way (on the unit circle, or a real reciprocal pair);
- the gain: the same power of |H| over 0..11 kHz.
Each row is written as c0', c1' (2^-23, c1' may pass 1) and k2, k3 (2^-16): at run time
c2' = k2 c2 and c3' = k3 c2, c2 the row's (times the output stage's gain, which q = c3 / c2
does not see). Rows whose c2 is 0 keep c3 (k3 is then c3' / c3, flagged by k2 = 0).

Usage: python tools/pi_metal_half_rows.py   (after md_port.py: it reads audio/md-tables.c)
writes audio/native/pi_metal_half_rows.h.
"""
import cmath, math, pathlib, re

MOD = pathlib.Path(__file__).resolve().parents[1]


def table(text: str, name: str) -> list[int]:
    m = re.search(r'const uint32_t %s\[512\]=\{(.*?)\};' % name, text, re.S)
    words = [int(w, 0) for w in re.findall(r'0x[0-9a-fA-F]+|\d+', m.group(1))]
    assert len(words) == 512, name
    return [w - (1 << 24) if w & 0x800000 else w for w in words]


def half_roots(r1: complex, r2: complex) -> tuple[complex, complex]:
    """two roots (a conjugate pair or two reals) for two steps at once"""
    def one(p: complex) -> complex:
        if abs(p.imag) < 1e-12:
            return complex(-p.real * p.real if p.real < 0 else p.real * p.real, 0.0)
        t = abs(cmath.phase(p))
        m = abs(p) ** 2
        if t <= math.pi / 2:
            return cmath.rect(m, 2 * t if p.imag > 0 else -2 * t)
        return complex(-m, 0.0)
    return one(r1), one(r2)


def response(a: float, b: float, c2: float, c3: float, w: float) -> float:
    z = cmath.exp(1j * w)
    num = abs(c3 + 2 * c2 * math.cos(w))
    den = abs(1 - a / z - b / (z * z))
    return (num / den) ** 2 if den > 1e-12 else 0.0


def row_half(c0: int, c1: int, c2: int, c3: int) -> tuple[int, int, int, int]:
    s = 1.0 / (1 << 23)
    a, b, g2, g3 = (1 + 2 * c1 * s), c0 * s, c2 * s, c3 * s
    p = cmath.sqrt(a * a + 4 * b)
    h1, h2 = half_roots((a + p) / 2, (a - p) / 2)
    ah, bh = (h1 + h2).real, -(h1 * h2).real
    if g2 != 0.0:
        q = g3 / g2
        zp = cmath.sqrt(q * q - 4)
        z1, z2 = half_roots((-q + zp) / 2, (-q - zp) / 2)
        qh = -(z1 + z2).real                       # c3' / c2' for c2 (z^2 + 1) + c3 z, roots z1 z2 = 1
    else:
        qh = None
    grid = [math.pi / 2 * (i + 0.5) / 256 for i in range(256)]
    full = sum(response(a, b, g2, g3, w) for w in grid)
    if qh is not None:                             # c2' with c2's sign, |H'| matched in power
        unit = sum(response(ah, bh, 1.0, qh, 2 * w) for w in grid)
        c2h = math.copysign(math.sqrt(full / unit), g2) if unit > 0 else 0.0
        k2, k3 = c2h / g2, qh * c2h / g2
    else:                                          # c2 = 0: the numerator is c3 alone
        unit = sum(response(ah, bh, 0.0, 1.0, 2 * w) for w in grid)
        c3h = math.copysign(math.sqrt(full / unit), g3) if unit > 0 and g3 else 0.0
        k2, k3 = 0.0, (c3h / g3 if g3 else 0.0)
    c1h = (ah - 1) / 2
    q16 = lambda v: max(-(1 << 31), min((1 << 31) - 1, int(round(v * 65536))))
    q23 = lambda v: max(-(1 << 31), min((1 << 31) - 1, int(round(v * (1 << 23)))))
    return q23(bh), q23(c1h), q16(k2), q16(k3)


def main() -> None:
    text = (MOD / 'audio/md-tables.c').read_text()
    out = ['/* SPDX-License-Identifier: GPL-2.0-or-later',
           ' * Generated by tools/pi_metal_half_rows.py from audio/md-tables.c; do not edit.',
           ' * PI-RC, CC and HH\'s filter rows at half rate (native/pi_metal_half.c): c0\', c1\' in',
           ' * 2^-23, k2, k3 in 2^-16 (c2\' = k2 c2, c3\' = k3 c2; k2 = 0: c3\' = k3 c3). */']
    for bank in ('a', 'b'):
        words = table(text, 'md_pi_cc_curve_' + bank)
        rows = [row_half(*words[4 * r:4 * r + 4]) for r in range(128)]
        out.append('static const int32_t md_mh_rows_%s[128][4]={' % bank)
        out += ['{%d,%d,%d,%d},' % r for r in rows]
        out.append('};')
    (MOD / 'audio/native/pi_metal_half_rows.h').write_text('\n'.join(out) + '\n')
    print('wrote audio/native/pi_metal_half_rows.h')


if __name__ == '__main__':
    main()
