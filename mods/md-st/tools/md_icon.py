"""tools/md_icon.py: an original pixel icon of a drum machine laid out as the Machinedrum (the
sixteen LEDs over the big data wheel, eight above and eight below, the display in the middle, its
screen landscape, five and four small round knobs, a band of buttons, sixteen square trig keys with their LEDs), drawn beside the voice list (main.c, the picker's STP_LIST_ART). No Elektron
artwork, name or logo: a drawing of our own.

Usage: python tools/md_icon.py   (writes md-icon.h)
"""
import pathlib

W, H = 56, 32
px = [[0] * W for _ in range(H)]


def on(x: int, y: int) -> None: px[y][x] = 1


def off(x: int, y: int) -> None: px[y][x] = 0


def rect(x0: int, y0: int, x1: int, y1: int, fill: bool = False) -> None:
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if fill or y in (y0, y1) or x in (x0, x1): on(x, y)


# the body: a box with rounded corners
rect(0, 0, W - 1, H - 1)
for x, y in ((0, 0), (W - 1, 0), (0, H - 1), (W - 1, H - 1)): off(x, y)
# the sixteen LEDs over the data wheel: eight above, eight below
for k in range(8): on(2 + 2 * k, 5); on(2 + 2 * k, 7)
# the big data wheel: a round disc, nine pixels across
for dy, row in enumerate(('..#####..', '.#######.', '#########', '#########', '#########',
                          '#########', '#########', '.#######.', '..#####..')):
    for dx, c in enumerate(row):
        if c == '#': on(5 + dx, 10 + dy)
# the display: its black surround a plain square, the screen in its lower half lit, landscape
rect(18, 4, 32, 18)
rect(20, 10, 30, 16, fill=True)
for x in range(21, 27): off(x, 12)
for x in range(21, 29): off(x, 14)
# the knobs, small rings: five on the top row; a button and four knobs under them
def knob(x0: int, y0: int) -> None:
    for dy, row in enumerate(('.#.', '#.#', '.#.')):
        for dx, c in enumerate(row):
            if c == '#': on(x0 + dx, y0 + dy)
for k in range(5): knob(34 + 4 * k, 9)
on(34, 14); on(35, 14); on(36, 14)
for k in range(1, 5): knob(34 + 4 * k, 13)
# the band of buttons under them, in three groups
for x0 in (4, 7, 10, 13, 20, 23, 26, 29, 35, 39, 46, 50):
    on(x0, 21); on(x0 + 1, 21)
# sixteen square trig keys, a pattern lit on their LEDs
for k, lit in enumerate('1000101010001001'):
    x = 4 + 3 * k
    rect(x, 26, x + 1, 27, fill=True)
    if lit == '1': on(x, 24); on(x + 1, 24)


def header() -> str:
    """md-icon.h: the icon a row two 32-bit words (no 64-bit shifts on the target), bit 31 of
    the first its left pixel, the top row first"""
    rows = []
    for r in px:
        v = 0
        for b in r: v = (v << 1) | b
        v <<= 64 - W
        rows.append((v >> 32, v & 0xffffffff))
    return ('/* SPDX-License-Identifier: GPL-2.0-or-later\n'
            ' * Generated by tools/md_icon.py; do not edit. An original drawing of a drum machine\n'
            ' * laid out as the Machinedrum, beside the voice list (main.c). A row is two words, bit 31\n'
            ' * of the first its left pixel, the top row first. */\n'
            '#define MD_ICON_W %d\n#define MD_ICON_H %d\n' % (W, H) +
            'static const unsigned int md_icon[MD_ICON_H][2]={\n' +
            ',\n'.join('    {0x%08xu,0x%08xu}' % r for r in rows) + '};\n')


if __name__ == '__main__':
    out = pathlib.Path(__file__).resolve().parents[1] / 'md-icon.h'
    out.write_bytes(header().encode())
    print('wrote', out.name)
