"""Formula-only Q31 envelope and SCF tables; no firmware input or runtime EMAC work.

All 128x128 attack/release pairs keep the running ColdFire's 32-step math.
The table is cold task-side data: the audio callback reads prepared rows.
scf-tables.h: SCF's 128 positions, OFF then 127 cutoffs log-spaced from 60
to 1000 Hz, their one-pole coefficients a = 1 - exp(-2 pi fc / 48000) (Q31)
and the rounded Hz the page shows. Also task-side: audio reads one prepared
coefficient, whatever the position.
time-tables.h: the texts the page shows for ATK and REL, their time
constants in ms.
"""
import argparse
import importlib.util
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def generated():
    spec=importlib.util.spec_from_file_location('compact_math',ROOT/'upstream/dsp.py')
    d=importlib.util.module_from_spec(spec);spec.loader.exec_module(d)
    def power(x):
        for _ in range(5):x=d.frac(x,x)
        return x
    k=[]
    for a in d.ATTACK:
        for r in d.RELEASE:
            total,rn=0,r
            for _ in range(32):
                # FI=1, RT=0: each product loses its low 23 bits BEFORE
                # accumulation into the 48-bit EMAC; MOVCLR drops 8 more.
                # The upstream ideal 64-bit frac2 differs by rare Q31 LSBs.
                total=((a*total>>23)+((0x7fffffff-a)*rn>>23))>>8
                rn=d.frac(rn,r)
            k.append(total)
    peaks=[]
    for raw in range(128):
        threshold=d.frac(d.THR_K,raw<<24)-d.THR_K
        lo,hi=256,0x7fffffff
        while lo<hi:
            mid=(lo+hi+1)//2
            if d.Compact.log(mid)<=threshold:lo=mid
            else:hi=mid-1
        peaks.append(lo)
    text='/* Generated by tools/generate_config_tables.py from upstream MIT formulas. */\n'
    for name,values in [('attack32',list(map(power,d.ATTACK))),
                         ('release32',list(map(power,d.RELEASE))),('ratio',d.RATIO),
                         ('idle_peak',peaks),('cross',k)]:
        text+='static const u32 comp_%s[%d]={\n'%(name,len(values))
        text+=''.join('    '+','.join('0x%08xu'%v for v in values[n:n+8])+',\n' for n in range(0,len(values),8))
        text+='};\n'
    return text


def time_constants(d):
    """ATK and REL positions 0..127 -> their time constants in ms, the
    formulas upstream/dsp.py builds ATTACK and RELEASE from (checked)."""
    atk=[0.1+99.9*(i/127)**2 for i in range(128)]
    rel=[10+1990*(i/127)**2.5 for i in range(128)]
    assert [d.coef(t) for t in atk]==d.ATTACK and [d.coef(t) for t in rel]==d.RELEASE
    return atk,rel


def ms_text(t):
    """At most four characters, no unit (the text also shows under the
    controls, where a longer one overlaps): 0.10 .. 9.99, 10.0 .. 99.9,
    100 .. 2000. The value pop-up's title carries the unit (ui.c)."""
    if round(t,2)<10:return '%.2f'%t
    if round(t,1)<100:return '%.1f'%t
    return '%d'%round(t)


def time_generated():
    spec=importlib.util.spec_from_file_location('compact_math',ROOT/'upstream/dsp.py')
    d=importlib.util.module_from_spec(spec);spec.loader.exec_module(d)
    text='/* Generated by tools/generate_config_tables.py: ATK and REL time constants, ms. */\n'
    for name,values in zip(('atk','rel'),time_constants(d)):
        strings=[ms_text(t) for t in values]
        assert all(len(s)<=4 for s in strings)
        text+='static const char *const comp_%s_text[128]={\n'%name
        text+=''.join('    '+','.join('"%s"'%s for s in strings[n:n+16])+',\n' for n in range(0,128,16))
        text+='};\n'
    return text


SCF_LOW,SCF_HIGH,SCF_RATE=60.0,1000.0,48000.0


def scf_cutoffs():
    """Position k (1..127) -> its cutoff in Hz; position 0 is OFF."""
    return [SCF_LOW*(SCF_HIGH/SCF_LOW)**((k-1)/126) for k in range(1,128)]


def scf_coefficients():
    return [0]+[round((1-math.exp(-2*math.pi*f/SCF_RATE))*2**31) for f in scf_cutoffs()]


def scf_generated():
    a=scf_coefficients();hz=[0]+[round(f) for f in scf_cutoffs()]
    text='/* Generated by tools/generate_config_tables.py: SCF, OFF then 60..1000 Hz log-spaced. */\n'
    text+='static const u32 comp_scf_coefficient[128]={\n'
    text+=''.join('    '+','.join('0x%08xu'%v for v in a[n:n+8])+',\n' for n in range(0,128,8))
    text+='};\nstatic const u16 comp_scf_hz[128]={\n'
    text+=''.join('    '+','.join('%d'%v for v in hz[n:n+16])+',\n' for n in range(0,128,16))
    return text+'};\n'


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,text in (('config-tables.h',generated()),('scf-tables.h',scf_generated()),('time-tables.h',time_generated())):
        path=ROOT/name
        if a.check:assert path.read_text()==text,'regenerate '+name
        else:path.write_text(text,newline='\n')
    print('PASS formula tables: 16384 cross coefficients, 128 SCF positions, ATK/REL ms texts; no firmware')
