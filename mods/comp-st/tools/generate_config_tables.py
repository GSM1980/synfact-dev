"""Formula-only Q31 envelope tables; no firmware input or runtime EMAC work.

All 128x128 attack/release pairs keep the running ColdFire's 32-step math.
The table is cold task-side data: the audio callback reads prepared rows.
"""
import argparse
import importlib.util
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def generated():
    spec=importlib.util.spec_from_file_location('compact_math',ROOT/'upstream/dsp.py')
    d=importlib.util.module_from_spec(spec);spec.loader.exec_module(d)
    def power(x):
        for _ in range(5):x=d.frac(x,x)
        return x
    k=[]
    for a in d.ATTACK:
        for r in d.RELEASE:
            total,rn=0,r
            for _ in range(32):
                # FI=1, RT=0: each product loses its low 23 bits BEFORE
                # accumulation into the 48-bit EMAC; MOVCLR drops 8 more.
                # The upstream ideal 64-bit frac2 differs by rare Q31 LSBs.
                total=((a*total>>23)+((0x7fffffff-a)*rn>>23))>>8
                rn=d.frac(rn,r)
            k.append(total)
    peaks=[]
    for raw in range(128):
        threshold=d.frac(d.THR_K,raw<<24)-d.THR_K
        lo,hi=256,0x7fffffff
        while lo<hi:
            mid=(lo+hi+1)//2
            if d.Compact.log(mid)<=threshold:lo=mid
            else:hi=mid-1
        peaks.append(lo)
    text='/* Generated by tools/generate_config_tables.py from upstream MIT formulas. */\n'
    for name,values in [('attack32',list(map(power,d.ATTACK))),
                         ('release32',list(map(power,d.RELEASE))),('ratio',d.RATIO),
                         ('idle_peak',peaks),('cross',k)]:
        text+='static const u32 comp_%s[%d]={\n'%(name,len(values))
        text+=''.join('    '+','.join('0x%08xu'%v for v in values[n:n+8])+',\n' for n in range(0,len(values),8))
        text+='};\n'
    return text


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'config-tables.h';text=generated()
    if a.check:assert path.read_text()==text,'regenerate config-tables.h'
    else:path.write_text(text,newline='\n')
    print('PASS formula tables: 16384 cross coefficients; no firmware')
