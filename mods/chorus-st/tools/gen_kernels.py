"""Write coeffs.inc: the chorus's own filter coefficients, from design.json.

    python mods/chorus-st/tools/gen_kernels.py

The decimator's sixteen taps (Q30, in design.json's position order) and the
halfband reconstructor's eight phase coefficients (Q31, four of them: the
filter is symmetric), as macros that load them into the kernels' registers. The
Digitone's tables (modulation LUT, HPF) are not here: tables.s takes them
from imported/, which tools/import_digitone.py rebuilds from the owner's OS
file. coeffs.inc is a checked-in build input; rerun this after changing
design.json. Until chorus 1.1 this script also wrote the kernels; since 1.2
they are hand-written in kernels.s (the same arithmetic).
"""
import json
from pathlib import Path
FOLDER=Path(__file__).resolve().parents[1]


def tables():
    design=json.loads((FOLDER/'design.json').read_text())
    positions=design['decimator']['positions']
    assert len(positions)==16 and max(positions)<24
    up=[round(x*2**31) for x in design['reconstructor']['phase_coefficients']]
    assert len(up)==8 and up==up[::-1], 'kernels.s keeps four of the eight: they must be symmetric'
    return {'chorus24_decimator_coeffs':[round(design['decimator']['coefficients'][k]*2**30) for k in positions],
            'chorus24_up_coeffs':up}


def text():
    """Macros that load each pass's coefficients into its registers (immediates:
    the bank's code sections hold instructions only), and the tables in
    .rodata for the emulator tests."""
    dec,up=tables().values()
    regs=['%d1','%d2','%d3','%d4','%d5','%d6','%d7','%a3']
    load=lambda r,v:('        movea.l #%d,%s' if r[1]=='a' else '        move.l #%d,%s')%(v,r)
    a=['| Generated by tools/gen_kernels.py from design.json; do not edit.']
    a+=['        .macro DEC_COEFFS_1']+[load(r,v) for r,v in zip(regs,dec[:8])]+['        .endm']
    a+=['        .macro DEC_COEFFS_2']+[load(r,v) for r,v in zip(regs,dec[8:])]+['        .endm']
    a+=['        .macro UP_COEFFS']+[load(r,v) for r,v in zip(regs,up[:4])]+['        .endm']
    a+=['        .macro COEFF_TABLES','        .section .rodata','        .balign 4']
    for name,values in tables().items():
        a+=['        .globl '+name,name+':']+['        .long %d'%v for v in values]
    a+=['        .text','        .endm']
    return '\n'.join(a)+'\n'


if __name__=='__main__':
    (FOLDER/'coeffs.inc').write_text(text(),newline='\n')
    print('wrote',FOLDER/'coeffs.inc')
