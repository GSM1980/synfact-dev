"""Generate widgets.h: the chorus's V56 widgets as native column bitmaps.

Same shapes as the V55 per-pixel drawings, one opaque 19x17 bitmap per
visible value step (native 400f70fa object, blitted by 400f8dac). Column-major
u32 words; bit 31 is row 0 = the box bottom y (frame y grows up).
Run once before building; the header is a checked-in build input.
"""
from pathlib import Path

W,H=19,17

def blank():return [[0]*H for _ in range(W)]
def put(img,x,y):
    if 0<=x<W and 0<=y<H:img[x][y]=1
def hline(img,x0,x1,y):
    for x in range(x0,x1+1):put(img,x,y)
def vline(img,x,y0,y1):
    for y in range(y0,y1+1):put(img,x,y)
def circle(img,cx,cy,r):
    x,y,e=r,0,1-r
    while x>=y:
        for px,py in ((x,y),(-x,y),(x,-y),(-x,-y),(y,x),(-y,x),(y,-x),(-y,-x)):put(img,cx+px,cy+py)
        y+=1
        if e<0:e+=2*y+1
        else:x-=1;e+=2*(y-x)+1

def hpf(k):
    img=blank();c=2+k;top,bottom=14,1
    vline(img,c,bottom,top-3);put(img,c+1,top-2);put(img,c+2,top-1)
    hline(img,c+3,16,top);vline(img,16,bottom,top)
    return img
def width(d):
    img=blank();circle(img,9-d,8,4);circle(img,9+d,8,4);return img
def cone(level):
    img=blank();cx=9
    for row in range(15):
        y=1+row;half=(14-row)//2
        put(img,cx-half,y);put(img,cx+half,y)
        if row==0:hline(img,cx-half,cx+half,y)
        elif row<level:
            for x in range(cx-half+1,cx+half):
                if x<=cx or (x+y)&1:put(img,x,y)
    return img

def words(img):
    return [sum(1<<(31-y) for y in range(H) if img[x][y]) for x in range(W)]

def table(name,images):
    rows=',\n'.join('    {'+','.join(f'0x{w:08x}u' for w in words(i))+'}' for i in images)
    return f'static const u32 {name}[{len(images)}][{W}]={{\n{rows}\n}};\n'

def main():
    mask=(0xffffffff<<(32-H))&0xffffffff
    text=('/* Generated by gen_chorus_widgets.py: 19x17 opaque column bitmaps. */\n'
          f'#define CHORUS_WIDGET_W {W}\n#define CHORUS_WIDGET_H {H}\n'
          f'static const u32 chorus_widget_mask[{W}]={{'+','.join(f'0x{mask:08x}u' for _ in range(W))+'};\n'
          +table('chorus_hpf_bits',[hpf(k) for k in range(11)])
          +table('chorus_width_bits',[width(d) for d in range(5)])
          +table('chorus_cone_bits',[cone(l) for l in range(15)]))
    (Path(__file__).resolve().parents[1]/'widgets.h').write_text(text,encoding='ascii',newline='\n')

if __name__=='__main__':main()
