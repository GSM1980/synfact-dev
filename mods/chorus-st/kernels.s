| The chorus's EMAC kernels (1.2: hand-written; 1.1's were generated by
| tools/gen_kernels.py, which now writes only coeffs.inc). Between
| chorus_hot_code and chorus_hot_code_end, the kernels every active block
| runs: chorus_place copies them to MAIN SRAM (ST_SRAM_CHORUS_CODE). They
| branch only within the span, take the state in A6 (state.inc) and keep it,
| and may change every other register. After the span, the rare paths, which
| stay in the bank's DDR. The arithmetic is 1.1's, bit for bit.
        .include "state.inc"
        .include "coeffs.inc"
        .text
        .balign 4
        .globl chorus_hot_code,chorus_hot_code_end
        .globl chorus_k_mixs,chorus_k_delay,chorus_k_up
chorus_hot_code:

| One track's four samples of the chunk into the four accumulators,
| acc -= gain x pcm (the native buses are inverted Q31): 18 bytes.
        .macro SLOT p,g
        move.l (\p)+,%d0
        msac.l \g,%d0,(\p)+,%d0,%acc0
        msac.l \g,%d0,(\p)+,%d0,%acc1
        msac.l \g,%d0,(\p)+,%d0,%acc2
        msac.l \g,%d0,%acc3
        .endm

| The mono send sum at stable gains: the block = sat(-sum gain x pcm), four
| samples at a time, every track into the accumulators, one saturating
| extraction per sample. One record (up to four tracks) stays in registers
| for the whole block; more are loaded and stored back each chunk, their
| pointers rewound at the end. The tracks' code is shared: it ends at A6.
chorus_k_mixs:
        move.l %a6,-(%sp)
        lea S_REC(%a6),%a1
        lea chorus_in+96,%a0
        pea 128(%a0)                            | the end
        moveq #1,%d0
        cmp.l S_NGRP(%a6),%d0
        bne.s .Lmg0
        movem.l (%a1),%d2-%d5/%a2-%a5           | gains, PCM
        movea.l R_ENTS(%a1),%a1
        lea .Lm1e(%pc),%a6
.Lm1:   jmp (.Lslots,%pc,%a1.l)
.Lm1e:  movclr.l %acc0,%d0
        movclr.l %acc1,%d1
        movclr.l %acc2,%d6
        movclr.l %acc3,%d7
        movem.l %d0-%d1/%d6-%d7,(%a0)
        lea 16(%a0),%a0
        cmpa.l (%sp),%a0
        bne.s .Lm1
        bra.s .Lmx
.Lmg0:  move.l S_NGRP(%a6),%d7
        move.l %a1,%d6
        lea .Lmge(%pc),%a6
.Lmc:   movea.l %d6,%a1
        move.l %d7,%d1
.Lmg:   movem.l (%a1),%d2-%d5/%a2-%a5
        move.l R_ENTS(%a1),%d0
        jmp (.Lslots,%pc,%d0.l)
.Lmge:  movem.l %a2-%a5,R_PTR(%a1)
        lea R_SIZE(%a1),%a1
        subq.l #1,%d1
        bne.s .Lmg
        movclr.l %acc0,%d2
        movclr.l %acc1,%d3
        movclr.l %acc2,%d4
        movclr.l %acc3,%d5
        movem.l %d2-%d5,(%a0)
        lea 16(%a0),%a0
        cmpa.l (%sp),%a0
        bne.s .Lmc
        movea.l %d6,%a1
        bsr.s chorus_rewind
.Lmx:   addq.l #4,%sp
        movea.l (%sp)+,%a6
        rts
.Lslots:
        SLOT %a2,%d2
        SLOT %a3,%d3
        SLOT %a4,%d4
        SLOT %a5,%d5
        jmp (%a6)
| The records' pointers back by a block (128 bytes): A1 = the records, D7 =
| the groups. Also the ramp's (cold, through this code's DDR original).
        .globl chorus_rewind
chorus_rewind:
1:      movem.l R_PTR(%a1),%a2-%a5
        lea -128(%a2),%a2
        lea -128(%a3),%a3
        lea -128(%a4),%a4
        lea -128(%a5),%a5
        movem.l %a2-%a5,R_PTR(%a1)
        lea R_SIZE(%a1),%a1
        subq.l #1,%d7
        bne.s 1b
        rts

| The two modulated taps, 16 frames into S_UP's block. Each tap's position
| (Q22 samples) moves linearly from its node to the next; per sample 1.1
| interpolated ring[idx] x frac + ring[idx+1] x (1 - frac), frac and idx
| recomputed from the position. Here the fraction (Q31) and 1 - frac step by
| the tap's step, and a carry out of the fraction moves the read pointer
| (the position's integer part changed): the same weights and samples, for
| steps under one sample a sample (else 1.1's loop, cold). The ring's
| mirror (hot.s) covers reads past 255.
        .macro DSETUP pos,step,frac,one,ptr,adj,tmp
        moveq #10,\tmp
        move.l \pos,\frac
        lsl.l \tmp,\frac
        lsr.l #1,\frac
        move.l #0x7fffffff,\one
        sub.l \frac,\one
        moveq #9,\tmp
        lsl.l \tmp,\step
        moveq #22,\tmp
        asr.l \tmp,\pos
        move.l S_WPOS(%a6),\tmp
        sub.l \pos,\tmp
        subq.l #1,\tmp
        andi.l #255,\tmp
        addq.l #1,\tmp
        movea.l #chorus_ring,\ptr
        lea (0,\ptr,\tmp\().l*4),\ptr
        movea.w #-4,\adj
        tst.l \step
        bpl.s 1f
        movea.w #4,\adj
1:
        .endm
chorus_k_delay:
        move.l %a6,-(%sp)
        move.l S_POS(%a6),%d0
        move.l S_POS+4(%a6),%d4
        sub.l %d0,%d4
        asr.l #4,%d4
        move.l S_POS+8(%a6),%d1
        move.l S_POS+12(%a6),%d5
        sub.l %d1,%d5
        asr.l #4,%d5
        move.l #0x400000,%d2                    | both steps in [-2^22, 2^22)?
        move.l %d4,%d3
        add.l %d2,%d3
        add.l %d5,%d2
        or.l %d3,%d2
        moveq #23,%d3
        lsr.l %d3,%d2
        bne .Lslow
        move.l %d0,-(%sp)                       | L's node and step, for later
        move.l %d4,-(%sp)
        move.l %d1,%d0
        move.l %d5,%d4
        bsr .Ltap                               | R
        move.l %d2,%d3
        move.l %d6,%d7
        move.l %d4,%d5
        movea.l %a3,%a4
        movea.l %a5,%a1
        move.l (%sp)+,%d4
        move.l (%sp)+,%d0
        bsr .Ltap                               | L
        lea chorus_up+64,%a0
        lea 128(%a0),%a2
.Ldl:   sub.l %d4,%d6
        add.l %d4,%d2
        bmi.s .Lwl
.Lbl:   move.l (%a3)+,%d0
        mac.l %d2,%d0,(%a3),%d1,%acc0
        mac.l %d6,%d1,%acc0
        sub.l %d5,%d7
        add.l %d5,%d3
        bmi.s .Lwr
.Lbr:   move.l (%a4)+,%d0
        mac.l %d3,%d0,(%a4),%d1,%acc1
        mac.l %d7,%d1,%acc1
        movclr.l %acc0,%d0
        add.l %d0,%d0
        sats.l %d0
        move.l %d0,(%a0)+
        movclr.l %acc1,%d0
        add.l %d0,%d0
        sats.l %d0
        move.l %d0,(%a0)+
        cmpa.l %a2,%a0
        bne.s .Ldl
        movea.l (%sp)+,%a6
        rts
.Lwl:   bchg #31,%d2
        bchg #31,%d6
        adda.l %a5,%a3
        bra.s .Lbl
.Lwr:   bchg #31,%d3
        bchg #31,%d7
        adda.l %a1,%a4
        bra.s .Lbr
| A tap from its node D0 and step D4: D2 = frac, D6 = 1 - frac, D4 = the
| step << 9, A3 = &ring[idx + 1], A5 = the pointer's move when frac wraps.
.Ltap:  DSETUP %d0,%d4,%d2,%d6,%a3,%a5,%d1
        rts
.Lslow: movea.l (%sp)+,%a6
        movea.l #chorus_cold_delay,%a0          | absolute: out of the span
        jmp (%a0)

| 24 -> 48 kHz, stereo: the 15-tap halfband (design.json), its identity
| phase a copy, its other phase eight symmetric coefficients (four registers).
| Two 24 kHz frames a pass share their loads: 32 products, 18 loads. A1 = 0:
| into the wet. A1 = a bus, D0 = a gain: each wet sample is returned there
| at once instead (bus = sat(bus + g x wet), the EMAC starting at the bus
| value, as chorus_k_ret): ev_main_mix's VOL, when it is the only return.
chorus_k_up:
        move.l %a6,-(%sp)
        movea.l %d0,%a4
        UP_COEFFS
        lea chorus_up+64,%a0
        pea 128(%a0)                            | the end
        move.l %a1,%d0
        bne.s .Lfused
        lea chorus_wet,%a1
.Lwet:  bsr.w .Lfir
        movclr.l %acc0,%d5
        movclr.l %acc1,%d6
        move.l -24(%a0),%d7
        movea.l -20(%a0),%a3
        movem.l %d5-%d7/%a3,(%a1)
        movclr.l %acc2,%d5
        movclr.l %acc3,%d6
        move.l -16(%a0),%d7
        movea.l -12(%a0),%a3
        movem.l %d5-%d7/%a3,16(%a1)
        lea 32(%a1),%a1
        lea 16(%a0),%a0
        cmpa.l (%sp),%a0
        bne.s .Lwet
        bra.s .Lupx
.Lfused:
        bsr.w .Lfir
        movclr.l %acc0,%d5                      | the frames' FIR outputs
        movclr.l %acc1,%d6
        movclr.l %acc2,%d7
        movclr.l %acc3,%a3
        movem.l (%a1),%d0/%a2/%a5-%a6
        move.l %d0,%acc0
        move.l %a2,%acc1
        move.l %a5,%acc2
        move.l %a6,%acc3
        mac.l %a4,%d5,-24(%a0),%d5,%acc0        | and the identity phase, loaded as they go
        mac.l %a4,%d6,-20(%a0),%d6,%acc1
        mac.l %a4,%d5,%acc2
        mac.l %a4,%d6,%acc3
        movclr.l %acc0,%d0
        movclr.l %acc1,%a2
        movclr.l %acc2,%a5
        movclr.l %acc3,%a6
        movem.l %d0/%a2/%a5-%a6,(%a1)
        movem.l 16(%a1),%d0/%a2/%a5-%a6
        move.l %d0,%acc0
        move.l %a2,%acc1
        move.l %a5,%acc2
        move.l %a6,%acc3
        mac.l %a4,%d7,-16(%a0),%d7,%acc0
        mac.l %a4,%a3,-12(%a0),%a3,%acc1
        mac.l %a4,%d7,%acc2
        mac.l %a4,%a3,%acc3
        movclr.l %acc0,%d0
        movclr.l %acc1,%a2
        movclr.l %acc2,%a5
        movclr.l %acc3,%a6
        movem.l %d0/%a2/%a5-%a6,16(%a1)
        lea 32(%a1),%a1
        lea 16(%a0),%a0
        cmpa.l (%sp),%a0
        bne.s .Lfused
.Lupx:  addq.l #4,%sp
        movea.l (%sp)+,%a6
        rts
| The FIR of frames j (ACC0/1) and j+1 (ACC2/3), A0 at frame j.
.Lfir:  move.l 8(%a0),%d0
        mac.l %d1,%d0,12(%a0),%d0,%acc2
        mac.l %d1,%d0,0(%a0),%d0,%acc3
        mac.l %d2,%d0,%acc2
        mac.l %d1,%d0,4(%a0),%d0,%acc0
        mac.l %d2,%d0,%acc3
        mac.l %d1,%d0,-8(%a0),%d0,%acc1
        mac.l %d3,%d0,%acc2
        mac.l %d2,%d0,-4(%a0),%d0,%acc0
        mac.l %d3,%d0,%acc3
        mac.l %d2,%d0,-16(%a0),%d0,%acc1
        mac.l %d4,%d0,%acc2
        mac.l %d3,%d0,-12(%a0),%d0,%acc0
        mac.l %d4,%d0,%acc3
        mac.l %d3,%d0,-24(%a0),%d0,%acc1
        mac.l %d4,%d0,%acc2
        mac.l %d4,%d0,-20(%a0),%d0,%acc0
        mac.l %d4,%d0,%acc3
        mac.l %d4,%d0,-32(%a0),%d0,%acc1
        mac.l %d3,%d0,%acc2
        mac.l %d4,%d0,-28(%a0),%d0,%acc0
        mac.l %d3,%d0,%acc3
        mac.l %d4,%d0,-40(%a0),%d0,%acc1
        mac.l %d2,%d0,%acc2
        mac.l %d3,%d0,-36(%a0),%d0,%acc0
        mac.l %d2,%d0,%acc3
        mac.l %d3,%d0,-48(%a0),%d0,%acc1
        mac.l %d1,%d0,%acc2
        mac.l %d2,%d0,-44(%a0),%d0,%acc0
        mac.l %d1,%d0,%acc3
        mac.l %d2,%d0,-56(%a0),%d0,%acc1
        mac.l %d1,%d0,-52(%a0),%d0,%acc0
        mac.l %d1,%d0,%acc1
        rts

chorus_hot_code_end:
        COEFF_TABLES

| ---- Rare paths, in DDR ------------------------------------------------------
| Contract (hot.s): A6 = state; D0-D1/A0-A1 change unless a path says more.

| The mix while gains ramp: each track's gain steps before every sample, as
| 1.1's; the records' gains are written back. May change D0-D7/A0-A5.
        .macro RSLOT p,g,s
        move.l (\p)+,%d0
        add.l \s(%a1),\g
        msac.l \g,%d0,(\p)+,%d0,%acc0
        add.l \s(%a1),\g
        msac.l \g,%d0,(\p)+,%d0,%acc1
        add.l \s(%a1),\g
        msac.l \g,%d0,(\p)+,%d0,%acc2
        add.l \s(%a1),\g
        msac.l \g,%d0,%acc3
        .endm
        .globl chorus_k_mixr
chorus_k_mixr:
        lea chorus_in+96,%a0
        move.l S_NGRP(%a6),%d7
        lea 128(%a0),%a1
        move.l %a1,S_END(%a6)
.Lrc:   lea S_REC(%a6),%a1
        move.l %d7,%d1
.Lrg:   movem.l (%a1),%d2-%d5/%a2-%a5
        move.l R_ENTR(%a1),%d6
        jmp (.Lrgs,%pc,%d6.l)
.Lrgs:  RSLOT %a2,%d2,R_STEP
        RSLOT %a3,%d3,R_STEP+4
        RSLOT %a4,%d4,R_STEP+8
        RSLOT %a5,%d5,R_STEP+12
        movem.l %d2-%d5/%a2-%a5,(%a1)
        lea R_SIZE(%a1),%a1
        subq.l #1,%d1
        bne.w .Lrg
        movclr.l %acc0,%d2
        movclr.l %acc1,%d3
        movclr.l %acc2,%d4
        movclr.l %acc3,%d5
        movem.l %d2-%d5,(%a0)
        lea 16(%a0),%a0
        cmpa.l S_END(%a6),%a0
        bne.w .Lrc
        lea S_REC(%a6),%a1
        movea.l #chorus_rewind,%a0              | its DDR original
        jmp (%a0)

| The track records from the gains, when a target changed or after a
| ramp (S_DIRTY). D7 = the mask of tracks with a target or current gain, in
| groups of four, the first group partial (its first slots skipped); each
| track's gain is its current one, its step (target - current) >> 5 per
| sample, and current becomes target (1.1's order: ascending tracks).
        .globl chorus_k_build
chorus_k_build:
        move.l S_TMASK(%a6),S_CMASK(%a6)
        subq.l #1,S_DIRTY(%a6)
        move.l %d7,%d0
        moveq #0,%d1
1:      tst.l %d0
        beq.s 2f
        move.l %d0,%d2
        subq.l #1,%d2
        and.l %d2,%d0
        addq.l #1,%d1
        bra.s 1b
2:      moveq #3,%d2
        add.l %d1,%d2
        lsr.l #2,%d2
        move.l %d2,S_NGRP(%a6)
        lsl.l #2,%d2
        sub.l %d1,%d2                   | first slot of the first group
        lea S_REC(%a6),%a1
        move.l %d2,%d0
        mulu.w #18,%d0
        move.l %d0,R_ENTS(%a1)
        move.l %d2,%d0
        mulu.w #34,%d0
        move.l %d0,R_ENTR(%a1)
        moveq #0,%d6                    | any step; the other groups are full
        move.l %d6,R_SIZE+R_ENTS(%a1)
        move.l %d6,R_SIZE+R_ENTR(%a1)
        move.l %d6,2*R_SIZE+R_ENTS(%a1)
        move.l %d6,2*R_SIZE+R_ENTR(%a1)
        lea S_TGT(%a6),%a2
        lea S_CUR(%a6),%a3
        movea.l #0x80003d50,%a4         | ST_TRACK_PCM(0)
        moveq #0,%d3
3:      btst %d3,%d7
        beq.s 4f
        move.l (%a3),%d0
        move.l (%a2),%d1
        move.l %d0,(0,%a1,%d2.l*4)
        move.l %a4,(R_PTR,%a1,%d2.l*4)
        move.l %d1,(%a3)
        sub.l %d0,%d1
        asr.l #5,%d1
        or.l %d1,%d6
        move.l %d1,(R_STEP,%a1,%d2.l*4)
        addq.l #1,%d2
        moveq #4,%d0
        cmp.l %d0,%d2
        bne.s 4f
        moveq #0,%d2
        lea R_SIZE(%a1),%a1             | past the third after track 11: not written
4:      addq.l #4,%a2
        addq.l #4,%a3
        lea 128(%a4),%a4
        addq.l #1,%d3
        moveq #8,%d0
        cmp.l %d0,%d3
        bne.s 5f
        movea.l #0x80003950,%a4         | ST_TRACK_PCM(8)
5:      moveq #12,%d0
        cmp.l %d0,%d3
        bne.s 3b
        move.l %d6,S_RAMP(%a6)
        rts

| Asleep, D7 = the tracks with a send: D0 = 1 when one of them has a nonzero
| sample this block.
| The ring's mirror (w < 48): entries 256..303 copy 0..47, so the delay reads
| past 255 without masking. A0 = &ring[w]. May change D0-D7.
        .globl chorus_cold_mirror
chorus_cold_mirror:
        movem.l (%a0),%d0-%d7
        movem.l %d0-%d7,1024(%a0)
        movem.l 32(%a0),%d0-%d7
        movem.l %d0-%d7,1056(%a0)
        rts

        .globl chorus_cold_wake
chorus_cold_wake:
        move.l %d2,-(%sp)
        moveq #0,%d1
        movea.l #0x80003d50,%a0
1:      btst %d1,%d7
        beq.s 3f
        movea.l %a0,%a1
        moveq #4,%d2
2:      move.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        or.l (%a1)+,%d0
        bne.s 4f
        subq.l #1,%d2
        bne.s 2b
3:      lea 128(%a0),%a0
        addq.l #1,%d1
        moveq #8,%d0
        cmp.l %d0,%d1
        bne.s 5f
        movea.l #0x80003950,%a0
5:      moveq #12,%d0
        cmp.l %d0,%d1
        bne.s 1b
        moveq #0,%d0
        bra.s 6f
4:      moveq #1,%d0
6:      move.l (%sp)+,%d2
        rts

| Asleep and silent: the gains settle without a block; the records follow at
| the next one.
        .globl chorus_cold_settle
chorus_cold_settle:
        lea S_TGT(%a6),%a0
        lea S_CUR(%a6),%a1
        moveq #11,%d0
1:      move.l (%a0)+,(%a1)+
        subq.l #1,%d0
        bpl.s 1b
        move.l S_TMASK(%a6),%d0
        move.l %d0,S_CMASK(%a6)
        moveq #1,%d0
        move.l %d0,S_DIRTY(%a6)
        rts

| A0 = the Kit's FX record (or 0): the settings (params.c's chorus_decode),
| the words they came from, the return targets 2 v^2 and the HPF coefficient.
        .globl chorus_cold_decode
chorus_cold_decode:
        move.l %a2,-(%sp)
        movea.l %a0,%a2
        pea S_VAL(%a6)
        move.l %a2,-(%sp)
        jsr chorus_decode
        addq.l #8,%sp
        move.l %a2,S_FX(%a6)
        move.l %a2,%d0
        beq.s 1f
        move.w (%a2),%d0
        move.w %d0,S_KEY(%a6)
        move.w 0x34(%a2),%d0
        move.w %d0,S_KEY+2(%a6)
        move.w 0x48(%a2),%d0
        move.w %d0,S_KEY+4(%a6)
        move.w 0x4e(%a2),%d0
        move.w %d0,S_KEY+6(%a6)
        move.w 0x52(%a2),%d0
        move.w %d0,S_KEY+8(%a6)
        move.w 0x54(%a2),%d0
        move.w %d0,S_KEY+10(%a6)
        move.w 0x6e(%a2),%d0
        move.w %d0,S_KEY+12(%a6)
        move.w 0x8c(%a2),%d0
        move.w %d0,S_KEY+14(%a6)
1:      moveq #0,%d0
        move.w S_VAL+8(%a6),%d0
        mulu.w %d0,%d0
        add.l %d0,%d0
        move.l %d0,S_DES(%a6)
        moveq #0,%d0
        move.w S_VAL+10(%a6),%d0
        mulu.w %d0,%d0
        add.l %d0,%d0
        move.l %d0,S_DES+4(%a6)
        moveq #0,%d0
        move.w S_VAL+12(%a6),%d0
        mulu.w %d0,%d0
        add.l %d0,%d0
        move.l %d0,S_DES+8(%a6)
        moveq #0,%d0
        move.w S_VAL+4(%a6),%d0
        cmpi.l #0x7f00,%d0
        bls.s 2f
        move.l #0x7f00,%d0
2:      lsr.l #8,%d0
        movea.l #chorus24_hpf24,%a0
        move.l (0,%a0,%d0.l*4),%d0
        move.l %d0,S_HPC(%a6)
        movea.l (%sp)+,%a2
        rts

| No track with a send: a silent block in.
        .globl chorus_cold_silence
chorus_cold_silence:
        lea chorus_in+96,%a0
