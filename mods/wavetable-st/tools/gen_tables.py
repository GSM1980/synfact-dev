"""SP WAVETBL's constant tables, from formulas only (no firmware input).

    python mods/wavetable-st/tools/gen_tables.py          # writes mods/wavetable-st/tables.h

tests/wavetable_st_reference.py imports TABLES from here, so the C engine and
its Python reference use the same numbers. test_wavetable_st.py checks that
tables.h is what this script writes.
"""
from pathlib import Path

RATE = 48000
BLOCK = 32
C_MINUS_1 = 440.0 * 2 ** (-69 / 12)          # MIDI note 0
TOP_HZ = 28000.0                              # a level's top harmonic stays below (aliases land above 20 kHz)
SHOT_MIN, SHOT_MAX = 0.002, 30.0              # one-shot ANIM times, seconds (SPD 0 and 127)
BEATS = [1 / 16, 1 / 8, 3 / 16, 1 / 4, 3 / 8, 1 / 2, 3 / 4, 1, 3 / 2, 2, 3, 4, 6, 8, 16, 32, 64]


def tables():
    two32 = 2 ** 32
    # Phase increment per sample, octave 0 (MIDI 0..11.99), 1/16 semitone steps, Q8 extra bits.
    inc = [round(C_MINUS_1 * two32 / RATE * 2 ** (i / 192) * 256) for i in range(193)]
    # One-shot ANIM: Q32 progress per block for SPD 0..127, exponential from 2 ms to 30 s.
    shot = [max(1, min(0xffffffff, round(two32 * BLOCK / RATE / (SHOT_MIN * (SHOT_MAX / SHOT_MIN) ** (s / 127)))))
            for s in range(128)]
    # Looping ANIM: Q32 cycle progress per block = tempo (BPM x 120) * K / 256 for each division.
    loop = [round(two32 * BLOCK / (RATE * 60 * 120) / b * 256) for b in BEATS]
    # Level choice: level k (top harmonic (1024 >> k) - 1) while inc <= limit[k].
    limit = [int(TOP_HZ / RATE * two32 // ((1024 >> k) - 1)) for k in range(9)]
    return dict(inc=inc, shot=shot, loop=loop, limit=limit)


TABLES = tables()


def header():
    t = TABLES
    def rows(name, values, kind='wt_u32'):
        body = ',\n'.join('    ' + ','.join(f'{v}u' for v in values[i:i + 8]) for i in range(0, len(values), 8))
        return f'static const {kind} {name}[{len(values)}]={{\n{body}\n}};\n'
    return ('/* SPDX-License-Identifier: GPL-2.0-or-later\n'
            ' * Generated by tools/gen_tables.py from formulas only; do not edit. */\n'
            '#ifndef WT_TABLES_H\n#define WT_TABLES_H\n'
            '/* phase increment per sample at MIDI 0..12 in 1/16 semitones, Q8 extra */\n' + rows('wt_inc', t['inc']) +
            '/* one-shot ANIM progress per block, SPD 0..127 (2 ms .. 30 s), Q32 */\n' + rows('wt_shot', t['shot']) +
            '/* looping ANIM: progress per block = tempo (BPM x 120) * K / 256, 1/16 beat .. 64 beats */\n' + rows('wt_loop', t['loop']) +
            '/* highest phase increment for level 0..8 (top harmonic < 28 kHz) */\n' + rows('wt_limit', t['limit']) +
            '#endif\n')


if __name__ == '__main__':
    out = Path(__file__).resolve().parents[1] / 'tables.h'
    out.write_text(header(), encoding='utf-8', newline='\n')
    print('wrote', out.name)
