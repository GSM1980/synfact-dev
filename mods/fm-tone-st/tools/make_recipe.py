"""Maintainers only: FM TONE's full private sources -> the public skeletons and recipe.

    python mods/fm-tone-st/tools/make_recipe.py <Digitone OS 1.44 .syx> --from <dir>

<dir> holds the full sources, with the Digitone's bytes:
dsp.s, tables.s and ui-data.h. They never go in the repository. This writes
what does: dsp.s and tables.s (labels, relocations and .incbin of the bytes),
ui-data.h.in (the drawings' shapes) and digitone.json (the recipe that rebuilds
the bytes from an owner's OS file, tools/import_digitone.py). Run it after a
change to the full sources, then check that the bank is the same.
"""
import argparse
import os
import re
import struct
import sys
import tempfile
from pathlib import Path

FOLDER = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FOLDER.parents[1]))
from elekloader.sdk import build as sdk, elf
from elekloader.sdk.syntakt import donor
from elekloader.devices.syntakt import DEVICE

MAIN_LOAD = 0x40000400            # the Digitone's MAIN OS (devices/digitone_mk1.py)
REGIONS = [
    # the second CPU's image: FM voices, kernels, constants and waves
    {'name': 'audio', 'section': 7, 'start': 0, 'length': 126352},
    # MAIN OS 1.44 0x40231800..0x40275400: the small font, the dials' diamonds,
    # the ratio frames and the algorithm diagrams
    {'name': 'ui', 'section': 3, 'start': 0x40231800 - MAIN_LOAD, 'length': 0x43c00},
]
OBJECTS = {'dsp': ('.text',), 'tables': ('.rodata', '.data')}
HEADERS = {'.text': '.text', '.rodata': '.section .rodata,"a"', '.data': '.section .data,"aw"'}
# The drawings ui-data.h takes from the Digitone, and how each value is stored.
DRAWINGS = {'FM_ALGORITHM_PIXELS': 'u32', 'FM_DIAMOND_PIXELS': 'u32', 'FM_RATIO_FRAME_C': 'u32',
            'FM_RATIO_FRAME_B': 'u32', 'FM_HARM_WAVES': 'u8', 'FM_FONT_WIDTHS': 'u8', 'FM_FONT_GLYPHS': 'u8'}


def assemble(src, out):
    prefix = os.environ.get('ELEKLOADER_CROSS', DEVICE.toolchain['prefix'])
    sdk.run([prefix + 'as', *DEVICE.toolchain['asflags'], '-I', str(src.parent), '-o', str(out), str(src)])
    return elf.Elf.load(out)


def skeleton(name, obj):
    """An object -> (its skeleton source, {blob name: bytes})."""
    lines = ['| FM TONE %s: the Digitone\'s bytes, rebuilt from the owner\'s OS file by' % name,
             '| tools/import_digitone.py into imported/. Labels and relocations are ours.',
             '| Generated by tools/make_recipe.py.']
    blobs = {}
    # a relocation against a section symbol names the section's start
    starts = {obj.section(s).idx: '.L%s_%s' % (name, s.strip('.')) for s in OBJECTS[name]}
    for section in OBJECTS[name]:
        sec = obj.section(section)
        blob = 'imported/%s%s.bin' % (name, section)
        blobs[blob] = sec.data
        events = []
        for s in obj.symbols:
            if s.name and s.shndx == sec.idx:
                events.append((s.value, 0, s))
        for at, kind, sym, add in obj.relocs.get(sec.idx, []):
            if kind != elf.R_68K_32:
                raise ValueError('%s%s: relocation type %d' % (name, section, kind))
            target = sym.name or starts.get(sym.shndx)
            if not target:
                raise ValueError('%s%s: relocation against section %d' % (name, section, sym.shndx))
            events.append((at, 1, (target, add)))
        lines += [HEADERS[section], '.balign %d' % sec.align, starts[sec.idx] + ':']
        pos, functions = 0, []
        for at, kind, what in sorted(events, key=lambda e: (e[0], e[1])):
            if at > pos:
                lines.append('.incbin "%s",0x%x,0x%x' % (blob, pos, at - pos))
                pos = at
            if kind == 0:
                if what.bind:
                    lines.append('.globl %s' % what.name)
                lines.append('%s:' % what.name)
                if what.type == 2:
                    functions.append(what)
            else:
                sym, add = what
                lines.append('.long %s%s' % (sym, '+0x%x' % add if add > 0 else '-0x%x' % -add if add else ''))
                pos += 4
        if pos < len(sec.data):
            lines.append('.incbin "%s",0x%x,0x%x' % (blob, pos, len(sec.data) - pos))
        for f in functions:
            lines += ['.type %s,@function' % f.name, '.size %s,0x%x' % (f.name, f.size)]
    return '\n'.join(lines) + '\n', blobs


def drawings(header):
    """ui-data.h -> (its template, the drawings' bytes in template order)."""
    data = bytearray()

    def replace(m):
        name, value = m[1], m[2]
        if name not in DRAWINGS:
            return m[0]
        rows = re.findall(r'\{([^{}]*)\}', value) if value.startswith('{{') else [value[1:-1]]
        numbers = [[int(x) for x in row.split(',')] for row in rows]
        if len({len(r) for r in numbers}) != 1:
            raise ValueError(name + ': rows of different lengths')
        kind = DRAWINGS[name]
        for row in numbers:
            data.extend(struct.pack('>%d%s' % (len(row), 'I' if kind == 'u32' else 'B'), *row))
        shape = '%d,%d' % (len(numbers), len(numbers[0])) if value.startswith('{{') else str(len(numbers[0]))
        return '#define %s @%s:%s@' % (name, kind, shape)
    text = re.sub(r'^#define (\w+) (\{.*\})$', replace, header, flags=re.M)
    first = text.index('\n') + 1
    text = ('/* FM TONE drawings: tools/import_digitone.py writes imported/ui-data.h from\n'
            '   this template and the owner\'s Digitone OS file (digitone.json). */\n' + text[first:])
    return text, bytes(data)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('digitone', type=Path)
    p.add_argument('--from', dest='source', type=Path, required=True)
    a = p.parse_args()
    outputs = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name in OBJECTS:
            text, blobs = skeleton(name, assemble(a.source / (name + '.s'), Path(tmp) / (name + '.o')))
            (FOLDER / (name + '.s')).write_text(text, newline='\n')
            outputs.update(blobs)
    template, data = drawings((a.source / 'ui-data.h').read_text())
    (FOLDER / 'ui-data.h.in').write_text(template, newline='\n')
    outputs['imported/ui-data.bin'] = data
    recipe = donor.make('FM TONE', a.digitone.read_bytes(), 'digitone-mk1', ['1.44'], REGIONS, outputs)
    (FOLDER / 'digitone.json').write_text(donor.dumps(recipe), newline='\n')
    for o in recipe['outputs']:
        copied = sum(op[3] for op in o['ops'] if op[0] == 'copy')
        filled = sum(len(op[1]) // 2 * op[2] for op in o['ops'] if op[0] == 'fill')
        ours = sum(len(op[1]) // 2 for op in o['ops'] if op[0] == 'data')
        print('%-26s %6d bytes: %6d copied, %6d filled, %5d ours, %4d operations'
              % (o['name'], o['length'], copied, filled, ours, len(o['ops'])))


if __name__ == '__main__':
    main()
